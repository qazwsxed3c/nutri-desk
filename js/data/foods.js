/** Нормализует список исключений клиента в набор тегов и названий продуктов. */
export function exclusionTags(client) {
  const text = [
    ...(client?.anamnesis?.allergies ?? []),
    ...(client?.anamnesis?.intolerances ?? []),
    ...(client?.anamnesis?.dietPreferences ?? []),
    client?.anamnesis?.dietStyle ?? '',
  ].join(' ').toLowerCase()
  const tags = new Set()
  const mapping = [
    ['gluten', ['глютен', 'глют', 'целиак', 'пшениц', 'хлеб', 'без глютена']],
    ['lactose', ['лактоз', 'молок', 'молоч', 'безлактоз', 'творог', 'сыр']],
    ['eggs', ['яйц', 'яиц']],
    ['fish', ['рыб']],
    ['shellfish', ['морепродукт', 'кревет', 'ракообраз']],
    ['nuts', ['орех', 'миндал', 'грецк']],
    ['soy', ['соя', 'сою', 'тофу']],
    ['sesame', ['кунжут', 'тахини']],
    ['meat', ['мясо', 'мясн', 'говядин', 'свинин', 'птиц']],
  ]
  for (const [tag, words] of mapping) {
    if (words.some((word) => text.includes(word))) tags.add(tag)
  }
  const dietStyle = (client?.anamnesis?.dietStyle ?? '').toLowerCase()
  if (dietStyle.includes('веган') || dietStyle.includes('vegan')) {
    for (const tag of ['meat', 'fish', 'shellfish', 'eggs', 'lactose']) tags.add(tag)
  } else if (dietStyle.includes('вегетариан') || dietStyle.includes('vegetarian')) {
    for (const tag of ['meat', 'fish', 'shellfish']) tags.add(tag)
  }
  return tags
}

/** Разрешён ли продукт клиенту. */
export function foodAllowed(food, tags) {
  if (!food || !tags || tags.size === 0) return true
  return !(food.allergens ?? []).some((tag) => tags.has(tag))
}

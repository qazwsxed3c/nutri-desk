/** Строка поиска по названию, сортировка по релевантности. */
export function searchFoods(query, foods = BUILTIN_FOODS) {
  const q = String(query ?? '').trim().toLowerCase()
  if (!q) return foods
  return foods
    .map((food) => {
      const name = food.name.toLowerCase()
      let score = 0
      if (name === q) score = 100
      else if (name.startsWith(q)) score = 80
      else if (name.includes(q)) score = 60
      else if (food.id.includes(q)) score = 30
      return { food, score }
    })
    .filter((entry) => entry.score > 0)
    .sort((a, b) => b.score - a.score)
    .map((entry) => entry.food)
}

